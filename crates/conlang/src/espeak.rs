//! eSpeak NG pronunciation files, so a speech voice can say the language at once.
//!
//! The output is a voice file plus `<dictionary>_rules` and `<dictionary>_list` sources. Put the
//! voice file in `<espeak-ng-data>/lang/art/` and compile the rules there with
//! `ESPEAK_DATA_PATH=<espeak-ng-data> espeak-ng --compile=<dictionary>` run in the directory that
//! holds the two sources. eSpeak NG runs as a separate program (GPL-3.0); CFA4 only writes its
//! input files.

use crate::language::{Language, subtag};
use crate::settings::Stress;

/// The phoneme table every entry of [`crate::phoneme::CATALOG`] is defined in.
pub const PHONEME_TABLE: &str = "az";

/// The files eSpeak NG needs for one language.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EspeakFiles {
    /// Dictionary name: `art` + the language subtag (never an existing eSpeak NG dictionary).
    pub dictionary: String,
    /// Contents of the voice file (`lang/art/<dictionary>`).
    pub voice: String,
    /// Contents of `<dictionary>_rules`.
    pub rules: String,
    /// Contents of `<dictionary>_list` (empty: the rules cover every word).
    pub list: String,
}

impl Language {
    /// eSpeak NG files that pronounce every spelling of this language.
    pub fn espeak(&self) -> EspeakFiles {
        let dictionary = format!("art{}", subtag(self.tag.rsplit('-').next().unwrap_or("")));
        let stress_rule = match self.phonology.stress {
            Stress::Initial => 0,
            Stress::Second => 1,
            Stress::Penultimate => 2,
            Stress::Final => 3,
        };
        // The name is the user's text: keep it on one line.
        let name: String = self.name.chars().map(|c| if c.is_whitespace() { ' ' } else { c }).collect();
        let voice = format!("name {name}\nlanguage {}\nphonemes {PHONEME_TABLE}\ndictionary {dictionary}\nstressRule {stress_rule}\n", self.tag);

        // One `.group` per first letter, longest graphemes first inside each group.
        let mut graphemes: Vec<(String, String)> = self.phonology.orthography().graphemes().map(|(g, seg)| (g, seg.espeak())).collect();
        graphemes.sort_by(|a, b| {
            let first = |s: &str| s.chars().next();
            first(&a.0).cmp(&first(&b.0)).then(b.0.chars().count().cmp(&a.0.chars().count())).then(a.0.cmp(&b.0))
        });
        let mut rules = format!("// eSpeak NG rules for {name} ({}), generated by CFA4 from seed {}.\n", self.tag, self.seed);
        let mut group: Option<char> = None;
        for (g, phonemes) in &graphemes {
            let first = g.chars().next();
            if first != group {
                group = first;
                if let Some(c) = first {
                    rules.push_str(&format!("\n.group {c}\n"));
                }
            }
            rules.push_str(&format!("\t{g}\t{phonemes}\n"));
        }
        EspeakFiles { dictionary, voice, rules, list: String::new() }
    }
}

#[cfg(test)]
mod tests {
    use crate::{Language, Settings};

    #[test]
    fn files_cover_every_letter() -> Result<(), crate::ConlangError> {
        let l = Language::generate("Kh'zar", 11, &Settings::default())?;
        let f = l.espeak();
        assert_eq!(f.dictionary, "artkhzar");
        assert!(f.voice.contains("language art-x-khzar\n") && f.voice.contains("phonemes az\n"));
        for (g, _) in l.phonology.orthography().graphemes() {
            assert!(f.rules.lines().any(|line| line.split('\t').nth(1) == Some(g.as_str())), "{g}");
        }
        Ok(())
    }

    #[test]
    fn hostile_name_stays_on_one_line() -> Result<(), crate::ConlangError> {
        let l = Language::generate("a\u{2028}b c", 1, &Settings::default())?;
        assert_eq!(l.espeak().voice.lines().count(), 5);
        Ok(())
    }
}
